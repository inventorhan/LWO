let currentLanguage

export function normalizeLanguage(value) {
  return LANGUAGES.includes(value) ? value : 'Korean'
}

export function getLanguage() {
  if (currentLanguage !== undefined) return currentLanguage
  try {
    currentLanguage = normalizeLanguage(localStorage.getItem(LANGUAGE_KEY))
  } catch (error) {
    console.warn('Could not read the language preference:', error)
    currentLanguage = 'Korean'
  }
  return currentLanguage
}

export function setLanguage(language) {
  if (!LANGUAGES.includes(language)) throw new TypeError('Unsupported language')
  localStorage.setItem(LANGUAGE_KEY, language)
  currentLanguage = language
}

export function syncLanguage(language) {
  currentLanguage = normalizeLanguage(language)
  return currentLanguage
}

export function lwoText(text, params = {}) {
  const entry = Object.prototype.hasOwnProperty.call(translations, text) ? translations[text] : null
  const language = getLanguage()
  const result = entry && language !== 'Korean' ? entry[language === 'English' ? 0 : 1] : text
  return result.replace(/\{(\w+)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match)
}
